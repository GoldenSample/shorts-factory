def main() -> int:
    WORK.mkdir(exist_ok=True)
    OUT.mkdir(exist_ok=True)
    scenes = []
    for tag, imager, voice_text, sub in SCENES:
        img = imager()
        if not img or not Path(img).exists():
            print(f"  {tag}: нет кадра — СТОП")
            return 1
        vp = WORK / f"{tag}_voice.mp3"
        if not tts(voice_text, vp):
            print(f"  {tag}: нет голоса — СТОП")
            return 1
        sc = build_scene(tag, Path(img), vp, sub,
                         kenburns=(Path(img).name == "src_woot.png"))
        if not sc:
            return 1
        print(f"  {tag}: {ffdur(sc):.1f}с")
        scenes.append(sc)
    total = sum(ffdur(s) for s in scenes)
    print(f"суммарно: {total:.1f}с")
    return 0 if assemble(scenes, "short_samsung_9100.mp4") else 1


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
