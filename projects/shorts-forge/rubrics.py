class MovesRefused(RuntimeError):
    """Отказ замка ходов: сценарий не выпускается в озвучку и сборку. Сообщение = причины по-русски."""


def _grams(text: str, n: int) -> set[str]:
    w = re.findall(r"[а-яёa-z0-9]+", text.lower().replace("ё", "е"))
    return {" ".join(w[i:i + n]) for i in range(len(w) - n + 1) if sum(len(x) >= 4 for x in w[i:i + n]) >= 2}


_EXAMPLE_GRAMS = set().union(*(_grams(p, 4) for p in EXAMPLE_PHRASES))


def copy_hits(text: str) -> list[str]:
    """Куски по 4 слова подряд (из них не меньше двух длинных), общие с готовыми фразами-примерами."""
    return sorted(_grams(text, 4) & _EXAMPLE_GRAMS)


def detect_moves(text: str) -> dict[str, int]:
    """Сколько раз в тексте стоит каждый подписной ход."""
    out = {}
    for c, rx in SIGNATURE.items():
        n = len(re.findall(rx, text, re.I))
        if n:
            out[c] = n
    return out


def journal_read(path: Path | None = None) -> list[dict]:
    """Журнал ходов канала по порядку роликов. Битая строка = отказ: замок на производстве не угадывает."""
    p = Path(path or JOURNAL)
    if not p.exists():
        return []
    out = []
    for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            e = json.loads(line)
        except ValueError as ex:
            raise MovesRefused(f"журнал ходов {p} битый в строке {i}: {ex}") from ex
        if not isinstance(e, dict) or "id" not in e:
            raise MovesRefused(f"журнал ходов {p}: строка {i} без id")
        out.append(e)
    return out


def _order(roll_id: str, salt: str, codes) -> list[str]:
    return sorted(codes, key=lambda c: hashlib.sha1(f"{roll_id}|{salt}|{c}".encode()).hexdigest())


def _freq_problems(hist: list[dict], used, hook: str | None, finale: str | None) -> list[str]:
    """Нарушения частоты, если к журналу hist добавить ролик с такими ходами."""
    probs = []
    if "П07" in used and any("П07" in (e.get("used") or {}) for e in hist[-(P07_WINDOW - 1):]):
        probs.append(f"«нет, погоди» (П07) уже был в последних {P07_WINDOW - 1} роликах: не чаще 1 из {P07_WINDOW}")
    for key, val in (("hook", hook), ("finale", finale)):
        last = [e.get(key) for e in hist[-RUN_MAX:]]
        if val and len(last) == RUN_MAX and all(x == val for x in last):
            probs.append(f"{'хук' if key == 'hook' else 'финал'} {val} уже {RUN_MAX} ролика подряд")
    if finale == VERDICT_FINALE and hist and hist[-1].get("finale") == VERDICT_FINALE:
        probs.append("финал-приговор (Ф2) два ролика подряд")
    return probs


def assign_moves(roll_id, line: str = "И", path: Path | None = None) -> dict:
    """Назначить ролику ходы по журналу: линия «И» = хук Х, 1-2 хода П, финал Ф; «новости» = 1-2 приёма голоса В, финал Ф
    (хук новостей = первый кадр рубрики). Выбор детерминирован по id, частоты журнала соблюдены. Перегенерация того же id не
    считает саму себя."""
    roll_id = str(roll_id)
    hist = [e for e in journal_read(path) if e.get("id") != roll_id]
    hook = None
    if line == "И":
        hook = next(h for h in _order(roll_id, "hook", HOOK_BANK) if not _freq_problems(hist, {}, h, None))
    finale = next(f for f in _order(roll_id, "finale", FINALE_BANK) if not _freq_problems(hist, {}, None, f))
    pool = MOVE_BANK if line == "И" else VOICE_MOVES
    k = 1 + int(hashlib.sha1(f"{roll_id}|k".encode()).hexdigest(), 16) % 2
    moves = [m for m in _order(roll_id, "move", pool) if not _freq_problems(hist, {m: 1}, None, None)][:k]
    return {"id": roll_id, "line": line, "hook": hook, "moves": moves, "finale": finale}


def moves_block(mv: dict) -> str:
    """Блок ХОДЫ РОЛИКА для промпта: только назначенное, механикой. Машинная строка «ХОДЫ:» читается parse_moves()."""
    codes = [c for c in [mv.get("hook"), *mv.get("moves", []), mv.get("finale")] if c]
    banned = [f"{c} {ALL_MOVES[c].split(':')[0]}" for c in SIGNATURE if c not in mv.get("moves", [])]
    rows = []
    if mv.get("hook"):
        rows.append(f"  - хук {mv['hook']}: {HOOK_BANK[mv['hook']]}. Первая реплика по этой механике, своими словами и фактами ролика.")
    rows += [f"  - ход {m}: {ALL_MOVES[m]}" for m in mv.get("moves", [])]
    rows.append(f"  - финал {mv['finale']}: {FINALE_BANK[mv['finale']]}. Петля ролика закрыта (закон 15.10).")
    return ("ХОДЫ РОЛИКА (назначены журналом канала, rubrics.assign_moves: у каждого ролика свои; других приметных ходов не брать):\n"
            f"ХОДЫ: {','.join(codes)} (ролик {mv.get('id') or '-'})\n" + "\n".join(rows) + "\n"
            f"  - НЕ БРАТЬ в этом ролике: {'; '.join(banned) or 'нет'}; готовые фразы и хвосты из прошлых роликов и примеров не повторять.")


def parse_moves(text: str) -> dict | None:
    """Назначение из строки «ХОДЫ: Х05,П02,Ф3 (ролик news:12)» в теме или промпте; нет строки = None."""
    m = re.search(r"ХОДЫ:\s*((?:[ХПВФ]\d{1,2}\s*,?\s*)+)(?:\(ролик ([^)]*)\))?", text or "")
    if not m:
        return None
    codes = re.findall(r"[ХПВФ]\d{1,2}", m.group(1))
    if not all(c in ALL_MOVES for c in codes) or not any(c in FINALE_BANK for c in codes):
        return None
    hook = next((c for c in codes if c in HOOK_BANK), None)
    rid = (m.group(2) or "").strip()
    return {"id": None if rid in ("", "-") else rid, "line": "И" if hook else "новости", "hook": hook,
            "moves": [c for c in codes if c in MOVE_BANK or c in VOICE_MOVES], "finale": next(c for c in codes if c in FINALE_BANK)}


def lint_moves(text: str, mv: dict | None) -> list[str]:
    """Проблемы ходов сценария. mv = назначение (None = ходов не назначено: любой подписной ход вне назначения)."""
    probs, assigned = [], set((mv or {}).get("moves", []))
    for code, n in detect_moves(text).items():
        hit = re.search(SIGNATURE[code], text, re.I).group(0)
        if code not in assigned:
            probs.append(f"ход вне назначения: «{hit}» ({code} {ALL_MOVES[code].split(':')[0]} ролику не назначен)")
        elif n > 1:
            probs.append(f"ход {code} {n} раза за ролик: «{hit}» один раз")
    m = TAIL_COPY.search(text)
    if m:
        probs.append(f"готовый хвост из примера: «{m.group(0)}», финал словами этого ролика")
    hits = copy_hits(text)
    if hits:
        probs.append(f"копия готовой фразы-примера: «{hits[0]}»" + (f" и ещё {len(hits) - 1}" if len(hits) > 1 else ""))
    return probs


def record_moves(mv: dict, text: str, path: Path | None = None) -> dict:
    """Дверь сценария в озвучку и сборку: линтер ходов и сторож частоты по журналу, потом строка в журнал. Отказ = MovesRefused.
    Тот же id перезаписывается на своём месте (перегенерация ролика), частота меряется по роликам до него."""
    if not mv or not mv.get("id") or not mv.get("finale"):
        raise MovesRefused("ролику не назначены ходы (нет id или финала): сценарий без назначения не выпускается")
    p = Path(path or JOURNAL)
    entries = journal_read(p)
    pos = next((i for i, e in enumerate(entries) if e.get("id") == mv["id"]), len(entries))
    used = detect_moves(text)
    probs = lint_moves(text, mv) + _freq_problems(entries[:pos], used, mv.get("hook"), mv["finale"])
    if probs:
        raise MovesRefused("; ".join(probs))
    e = {"id": mv["id"], "line": mv.get("line"), "hook": mv.get("hook"), "moves": mv.get("moves", []), "finale": mv["finale"],
         "used": used, "sha": hashlib.sha256(text.encode("utf-8")).hexdigest()[:16], "ts": time.strftime("%Y-%m-%dT%H:%M:%S")}
    entries = entries[:pos] + [e] + entries[pos + 1:]
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in entries), encoding="utf-8")
    os.replace(tmp, p)
    return e


def detect(title: str, desc: str = "", events: list[str] | None = None) -> list[dict]:
    """Применимые рубрики, сильнейшая первой. Нужна и зацепка в заголовке, и своя фактура в тексте."""
    head = (title or "").lower(); full = f"{title} {desc}".lower(); ev = " ".join(events or []).lower()
    out = []
    if re.search(r"смартфон|планшет|iphone|ipad|galaxy s|часы|наушник", head):   # канал про ПК: мобильное мимо рубрик
        return out
    for r in RUBRICS:
        if not r["trigger"]: continue
        hit = re.search(r["trigger"], head) or (r["key"] == "it_burns" and re.search(r"failure|security", ev))
        if r["key"] == "free_useful" and re.search(r"предзаказ|в продаж|поступил|цена|стоимост|бандл|\[|в подарок|\bигр[аыу]\b|шутер", head): hit = None   # покупка и игры не «бесплатно полезно»
        if r["key"] == "ru_market" and re.search(r"\bсша\b|\bес\b|европ|кита[йе]\w*\s+рын", head) and not re.search(r"росси|\bрф\b", head): hit = None   # чужой рынок
        if r["key"] == "taken_away" and head.rstrip().endswith("?"): hit = None   # вопрос форума, а не решение вендора
        if hit and re.search(r["need"], full) and re.search(HW, full):
            out.append(r)
    return sorted(out, key=lambda r: -(r["organic"] or 0))


def lift(r: dict | None) -> float:
    """Прирост органики рубрики к базе (0 = лента). Малая выборка: использовать как вес, а не как обещание."""
    return 0.0 if not r or not r["organic"] else round((r["organic"] - BASE_ORGANIC) / BASE_ORGANIC, 2)


def title_forms(r: dict, news_id: int | str) -> list[str]:
    forms = TITLE_FORMS[r["key"]]; k = int(hashlib.sha1(str(news_id).encode()).hexdigest(), 16) % len(forms)
