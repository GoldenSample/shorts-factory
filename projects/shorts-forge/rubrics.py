def lint(plan: dict, rubric: str | None = None, moves: dict | None = None) -> list[str]:
    """Проблемы раскадровки. Пустой список = слог чист. moves = назначение ходов ролика: тогда проверяются и ходы (lint_moves),
    а вердикт в последних сценах требуется только при финале Ф2."""
    scenes = plan.get("scenes", []); voices = [s.get("voice", "") for s in scenes]; allt = " ".join([plan.get("title", ""), plan.get("hook", "")] + voices)
    probs = []
    for rx in STAMPS:
        m = re.search(rx, allt, re.I)
        if m: probs.append(f"штамп пересказа: «{m.group(0)}»")
    if EMOJI.search(allt): probs.append("эмодзи в тексте ролика")
    m = MAT.search(allt)
    if m: probs.append(f"мат: «{m.group(0)}», голос Гора в шортсах без мата (рекламодатели режут ролик)")
    m = CHAT.search(allt)
    if m: probs.append(f"чат-маркер «{m.group(0)}»: голос прочитает его буквами")
    m = YOU_FORMAL.search(" ".join(voices))
    if m: probs.append(f"обращение «{m.group(0)}»: Гор говорит зрителю «ты» (в его твиттере «ты» в 6 раз чаще «вы»)")
    lens = [len(s.split()) for v in voices for s in SENT.split(v.strip()) if s.strip()]
    if len(lens) >= 6:
        hits = sum(x <= 4 for x in lens)
        if not hits: probs.append(f"ни одной фразы-удара до 4 слов из {len(lens)}: звучит лекцией (у Гора таких 31 %)")
        elif hits / len(lens) > 0.6: probs.append(f"метроном: {hits} из {len(lens)} фраз до 4 слов (у Гора 31 %), нужен фон полными фразами")
    first = (plan.get("hook") or "") + " " + (voices[0] if voices else "")
    if not re.search(r"\d|один|два|три|четыр|пят|шест|сем|восем|девят|десят|сот|тысяч|процент|рубл|ватт|градус|кадр", first, re.I):
        probs.append("в первой фразе нет цифры: зацепки нет")
    # Начало строки «нет вердикта в последних сценах» = имя правила для снятий словом Гора (drama_voice.waived, Р01 11.11
    # «Оставить действие»): текст после него можно менять, начало нет.
    if voices and not re.search(VERDICT, " ".join(voices), re.I):
        probs.append("нет вердикта в последних сценах и нигде в ролике (брать, ждать, не трогать, включать ...)")
    elif voices and moves and moves.get("finale") == VERDICT_FINALE and not re.search(VERDICT, " ".join(voices[-2:]), re.I):
        probs.append("нет вердикта в последних сценах: назначен финал Ф2 (приговор)")
    if moves is not None:
        said = " ".join(voices); hook = (plan.get("hook") or "").strip()
        probs += lint_moves(said + (" " + hook if hook and hook not in said else ""), moves)
    words = sum(len(v.split()) for v in voices)
    if words > 110: probs.append(f"начитка {words} слов: больше 60 секунд, одна мысль не держится")
    if len(plan.get("title", "")) > 60: probs.append(f"заголовок {len(plan['title'])} знаков, потолок 60")
    r = BY_KEY.get(rubric or "")
    if r:
        if r["chip"].lower() in plan.get("title", "").lower(): probs.append("название рубрики в заголовке: шаблон для детектора, убрать")
        if r["key"] == "ru_market" and not re.search(r"рубл|₽|росси|у нас|в рф|dns|ситилинк|импорт", allt, re.I):
            probs.append("рубрика РФ, а российского факта в тексте нет")
    return probs


def moves_selftest(tmp: Path) -> tuple[list[str], int]:
    """Тесты замка ходов: законный путь проходит, каждая дверь из аудита получает отказ. Пишет только в tmp."""
    fails, n = [], 0

    def case(name, cond):
        nonlocal n
        n += 1
        if not cond:
            fails.append(f"ходы: {name}")

    # 1. законный путь: 12 роликов И и 6 новостей подряд, частоты по журналу соблюдены, финалы и хуки разные
    j = tmp / "legal.jsonl"
    for i in range(12):
        mv = assign_moves(f"t{i}", "И", j)
        record_moves(mv, "Плата греется. " + ("Нет, погоди, всё иначе. " if "П07" in mv["moves"] else "") + "Счёт сошёлся.", j)
    for i in range(6):
        mv = assign_moves(f"n{i}", "новости", j)
        record_moves(mv, "Карта берёт 575 ватт. Брать только с родным кабелем.", j)
    es = journal_read(j)
    p07 = [1 if "П07" in (e.get("used") or {}) else 0 for e in es]
    # числа Гора буквально (1 из 4, не больше 2 подряд), а не константы замка: тест не должен мерить себя тем, что проверяет
    case("«погоди» чаще 1 из 4 на законном пути", all(sum(p07[i:i + 4]) <= 1 for i in range(len(p07))))
    for key in ("hook", "finale"):
        vals = [e.get(key) for e in es if e.get(key)]
        case(f"{key} больше 2 подряд на законном пути", all(len(set(vals[i:i + 3])) > 1 for i in range(len(vals) - 2)))
    fins = [e["finale"] for e in es]
    case("Ф2 два подряд", all(not (fins[i] == fins[i + 1] == VERDICT_FINALE) for i in range(len(fins) - 1)))
    case("финалы не разнообразны (меньше 4 типов на 18 роликов)", len(set(fins)) >= 4)
    case("хуки И не разнообразны (меньше 6 типов на 12)", len({e["hook"] for e in es if e.get("hook")}) >= 6)
    case("новостям назначен хук или ход монолога", all(not e.get("hook") and all(m in VOICE_MOVES for m in e["moves"]) for e in es[12:]))
    # 2-5. линтер: неназначенный ход, ход дважды, копия примера, готовый хвост; чистый текст проходит
    case("неназначенный «погоди» прошёл", any(p.startswith("ход вне назначения") for p in lint_moves("Нет, погоди. Всё иначе.", {"moves": ["П02"]})))
    case("«погоди» дважды прошёл", any("2 раза" in p for p in lint_moves("Нет, погоди. Подожди, ещё раз.", {"moves": ["П07"]})))
    case("копия хука HOOKS.md прошла", any(p.startswith("копия") for p in
         lint_moves("Если не можешь обнаружить характер, его нет. И всё же я его различал.", {"moves": []})))
    case("готовый хвост прошёл", any(p.startswith("готовый хвост") for p in lint_moves("Брать с родным кабелем. Так и живём.", {"moves": []})))
    case("ложное на чистом новостном тексте", not lint_moves("Память на шесть тысяч разогнали до восьми шестисот. Это сколько наносекунд? "
                                                              "Си-эль считают в тактах.", {"moves": []}))
    # 6. сторож частоты на двери: второй «погоди» подряд = отказ
    j2 = tmp / "freq.jsonl"
    record_moves({"id": "a", "line": "И", "hook": "Х01", "moves": ["П07"], "finale": "Ф1"}, "Нет, погоди. Иначе.", j2)
    try:
        record_moves({"id": "b", "line": "И", "hook": "Х02", "moves": ["П07"], "finale": "Ф3"}, "Подожди. Иначе.", j2)
        case("второй «погоди» в окне записан", False)
    except MovesRefused:
        case("второй «погоди» в окне записан", True)
    # 6б. сторож на двери: третий одинаковый финал, третий одинаковый хук, Ф2 два подряд = отказ
    def door(name, seq, f):
        jj = tmp / f"{name}.jsonl"
        try:
            for i, (hook, fin) in enumerate(seq):
                record_moves({"id": f"{name}{i}", "line": "И" if hook else "новости", "hook": hook, "moves": [], "finale": fin},
                             f"Реплика {i}. Итог сошёлся.", jj)
            case(f, False)
        except MovesRefused:
            case(f, len(journal_read(jj)) == len(seq) - 1)
    door("fin", [(None, "Ф3"), (None, "Ф3"), (None, "Ф3")], "третий одинаковый финал подряд записан")
    door("hook", [("Х05", "Ф1"), ("Х05", "Ф3"), ("Х05", "Ф4")], "третий одинаковый хук подряд записан")
    door("ver", [(None, "Ф2"), (None, "Ф2")], "финал-приговор Ф2 два подряд записан")
    # 7. битый журнал = отказ, а не угадывание
    j3 = tmp / "broken.jsonl"; j3.write_text("{oops\n", encoding="utf-8")
    try:
        assign_moves("x", "И", j3); case("битый журнал прошёл", False)
    except MovesRefused:
        case("битый журнал прошёл", True)
    # 8. промпт: блок ходов ровно один, ни голос, ни блок ходов не несут готовых фраз-примеров
    pb = prompt_block(None, 7)
    case("блок ХОДЫ в промпте не один раз", pb.count("ХОДЫ:") == 1)
    case("в блоке голоса готовая фраза-пример", not copy_hits(voice_block()) and not TAIL_COPY.search(voice_block()))
    case("в блоке ходов готовая фраза-пример", not copy_hits(moves_block(assign_moves("y", "И", tmp / "y.jsonl"))))
    # 9. разбор назначения из промпта обратно
    mv = assign_moves("rt", "И", tmp / "rt.jsonl"); back = parse_moves(moves_block(mv))
    case("parse_moves не вернул назначение", bool(back) and back["id"] == "rt" and back["hook"] == mv["hook"]
         and back["moves"] == mv["moves"] and back["finale"] == mv["finale"])
    # 10. сценарий без назначения не выпускается
    try:
        record_moves({"moves": []}, "текст", tmp / "noid.jsonl"); case("сценарий без назначения записан", False)
    except MovesRefused:
        case("сценарий без назначения записан", True)
    # 11. перегенерация того же ролика заменяет строку, а не добавляет
    record_moves({k: es[0][k] for k in ("id", "line", "hook", "moves", "finale")}, "Плата греется заново. Счёт сошёлся.", j)
    case("перегенерация добавила строку", len(journal_read(j)) == len(es))
    # 11б. охранная клауза: имя правила вердикта для снятий словом Гора не уехало (Р01 lint_waivers «нет вердикта в последних сценах»)
    nov = lint({"title": "t", "hook": "5090 берёт 575 ватт.", "scenes": [{"voice": "5090 берёт 575 ватт. Через один разъём."}]})
    case("имя правила вердикта сменилось: снятие Р01 сломается", any(p.startswith("нет вердикта в последних сценах") for p in nov))
    mid = lint({"title": "t", "hook": "5090 берёт 575 ватт.", "scenes": [{"voice": "5090 берёт 575 ватт. Брать с родным кабелем."},
                                                                        {"voice": "Разъём держит. Итог сошёлся."}]})
    case("вердикт в середине ролика не засчитан", not any(p.startswith("нет вердикта") for p in mid))
    # 12. исторический брак: мои образцы 05.10 с одним сухим хвостом получают отказ
    for t in ("Уже вылетает - в гарантию, разгонять поздно. Так и живём.", "Переходники с маркетплейса - не брать. У меня всё."):
        case(f"образец 05.10 прошёл: {t[-14:]}", any(p.startswith("готовый хвост") for p in lint_moves(t, {"moves": []})))
    return fails, n


def moves_replay(src: Path) -> int:
    """Прогон сторожа частоты на готовом корпусе роликов по порядку (lines.json: id -> текст или список текстов)."""
    d = json.loads(src.read_text(encoding="utf-8-sig"))
    items = list(d.items()) if isinstance(d, dict) else [(str(i), t) for i, t in enumerate(d)]
    hist, refused, copies = [], [], []
    for rid, text in items:
        text = " ".join(text) if isinstance(text, list) else str(text)
        used = detect_moves(text)
        if _freq_problems(hist, used, None, None):
            refused.append(rid)
        if copy_hits(text) or TAIL_COPY.search(text):
            copies.append(rid)
        hist.append({"id": rid, "used": used})
    p07 = [e["id"] for e in hist if "П07" in e["used"]]
    if refused:
        print(f"ИСТОРИЧЕСКИЙ БРАК ОТКАЗ: сторож частоты отказал {len(refused)} из {len(items)} ({', '.join(refused)}); «погоди» в {len(p07)}: {', '.join(p07)}")
    else:
        print(f"ЧАСТОТЫ ПРОШЛИ: {len(items)} роликов, «погоди» в {len(p07)}" + (f": {', '.join(p07)}" if p07 else ""))
    print("копии готовых фраз (линтер отказал бы): " + (", ".join(copies) if copies else "нет"))
    return 0


